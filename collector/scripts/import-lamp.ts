// Imports baselines from MBTA LAMP (Sprint 7, DEC-059). Run on a computer, not the Worker:
// it downloads the last N days of daily subway files (~1.6 MB each), keeps only summaries,
// and writes baselines.sql to load with:
//   npx wrangler d1 execute enroute-history --remote --file baselines.sql
//
// Usage: node scripts/import-lamp.ts [days=56]
// Downloads are cached in .lamp-cache/ (git-ignored), so a re-run does not fetch them again.

import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { asyncBufferFromFile, parquetReadObjects } from 'hyparquet'
import {
  headwayBaselines,
  toStopEvent,
  trainBaselines,
  type StopEvent,
} from '../src/baselines.ts'

const INDEX_URL = 'https://performancedata.mbta.com/lamp/subway-on-time-performance-v1/index.csv'
const CACHE = '.lamp-cache'
const days = Number(process.argv[2] ?? 56)

async function main() {
  mkdirSync(CACHE, { recursive: true })
  const index = await (await fetch(INDEX_URL)).text()
  // Columns: size_bytes,last_modified,service_date,file_url. Newest dates are last.
  const files = index
    .trim()
    .split('\n')
    .slice(1)
    .map((line) => line.split(','))
    .map(([, , date, url]) => ({ date, url }))
    .filter((f) => /^\d{4}-\d{2}-\d{2}$/.test(f.date) && f.url?.startsWith('https://performancedata.mbta.com/'))
    .sort((a, b) => a.date.localeCompare(b.date))
    .slice(-days)

  const events: StopEvent[] = []
  for (const [i, f] of files.entries()) {
    const path = `${CACHE}/${f.date}.parquet`
    if (!existsSync(path)) {
      const response = await fetch(f.url)
      if (!response.ok) throw new Error(`${f.date}: HTTP ${response.status}`)
      writeFileSync(path, Buffer.from(await response.arrayBuffer()))
    }
    const rows = await parquetReadObjects({ file: await asyncBufferFromFile(path) })
    let kept = 0
    for (const row of rows) {
      const e = toStopEvent(row as Record<string, unknown>)
      if (e) {
        events.push(e)
        kept++
      }
    }
    process.stdout.write(`${i + 1}/${files.length} ${f.date}: ${kept} of ${rows.length} rows kept\n`)
  }

  const headways = headwayBaselines(events)
  const trains = trainBaselines(events)
  const from = Number(files[0].date.replaceAll('-', ''))
  const to = Number(files.at(-1)!.date.replaceAll('-', ''))

  const q = (s: string) => `'${s.replaceAll("'", "''")}'`
  const sql = [
    '-- Generated by scripts/import-lamp.ts. Replaces all baselines (re-running changes nothing).',
    'DELETE FROM baseline_headways;',
    'DELETE FROM baseline_trains;',
    'DELETE FROM baseline_source;',
    ...headways.map(
      (h) =>
        `INSERT INTO baseline_headways VALUES (${q(h.line)}, ${h.directionId}, ${q(h.dayType)}, ${h.hour}, ${h.samples}, ${h.medianSeconds}, ${h.p90Seconds}, ${h.scheduledMedianSeconds}, ${h.reliableShare.toFixed(4)});`,
    ),
    ...trains.map(
      (t) =>
        `INSERT INTO baseline_trains VALUES (${q(t.line)}, ${q(t.dayType)}, ${t.hour}, ${t.typicalTrains}, ${t.days});`,
    ),
    `INSERT INTO baseline_source VALUES (1, 'MBTA LAMP subway on-time performance', ${from}, ${to}, ${files.length}, ${events.length}, ${Date.now()});`,
  ].join('\n')
  writeFileSync('baselines.sql', sql + '\n')
  console.log(
    `\n${files.length} days (${files[0].date} to ${files.at(-1)!.date}), ${events.length} stop events -> ${headways.length} headway rows, ${trains.length} train rows. Wrote baselines.sql (${(sql.length / 1024).toFixed(0)} KB).`,
  )
}

await main()
